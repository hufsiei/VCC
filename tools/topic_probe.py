def export_csv(path, prefix="마르부르크 ", round_no=3):
    """확인용 3·4차를 run_eval용 csv로(질문 앞에 학교 이름). 답해야 할 질문 = 답변, 근거 없는 칸·보고서에 없는 주제 = 보류."""
    pos, gap, neg = ROUNDS[round_no]
    rows = [{"번호": str(i), "질문": (school or prefix) + q, "기대결과": "답변", "유형": f"주제 {item}"}
            for i, (school, q, item) in enumerate(pos, start=1)]
    rows += [{"번호": str(len(rows) + i), "질문": (school or prefix) + q, "기대결과": "보류", "유형": "근거 없는 칸"}
             for i, (school, q) in enumerate(gap, start=1)]
    rows += [{"번호": str(len(rows) + i), "질문": (school or prefix) + q, "기대결과": "보류", "유형": "없는 주제"}
             for i, (school, q) in enumerate(neg, start=1)]
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(f"저장: {path} (확인용 {round_no}차 {len(rows)}문항 — 답변 기대 {len(pos)} · 근거 없는 칸 보류 {len(gap)} · 없는 주제 보류 {len(neg)})")

