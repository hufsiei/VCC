def items_of(q, table):
    out = []
    for pattern, nums in table:
        if re.search(pattern, q):
            out += [n for n in nums if n not in out]
    return out


def score(table, pos, neg):
    hit = [(q, want, items_of(q, table)) for q, want in pos]
    good = [h for h in hit if h[1] in h[2]]
    none = [h for h in hit if not h[2]]
    wrong = [h for h in hit if h[2] and h[1] not in h[2]]
    negs = [(q, items_of(q, table)) for q in neg if items_of(q, table)]
    return good, none, wrong, negs


def report(name, table, pos, neg, show=True):
    good, none, wrong, negs = score(table, pos, neg)
    print(f"[{name}] 맞는 문항 {len(good)}/{len(pos)} · 주제 못 찾음 {len(none)} · 다른 문항으로 감 {len(wrong)} · 없는 주제인데 잡음 {len(negs)}/{len(neg)}")
    if show:
        for q, want, got in none:
            print(f"    못 찾음({want}): {q}")
        for q, want, got in wrong:
            print(f"    다른 문항({want}→{got}): {q}")
        for q, got in negs:
            print(f"    ✗ 없는 주제인데 {got}: {q}")
    return good, none, wrong, negs


