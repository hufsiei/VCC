# 주의: 파이썬 정규식의 \w는 한글도 포함한다. 한글 바로 뒤에 붙여 쓴 번호('번호010-…')를 잡으려면
#       앞 경계를 \w가 아니라 영문·숫자로만 막아야 한다(_NB).
import re

_NB = r"(?<![0-9A-Za-z])"          # 앞이 영문·숫자가 아님(한글·공백·기호는 허용)
# 숫자 바로 뒤에 붙으면 금액·수량이지 학번·주소가 아니다
_UNIT = r"(?:원|만|천|억|유로|달러|엔|파운드|프랑|크로나|코루나|루블|헤알|개|명|번(?!길|지)|시간|분|초|주|일|년|월|학기|학년|학점|점|%|가지|군데|살|층|등|차|위|회|km|m\b|kg)"
_MONEY = r"(?:원|만|천|억|유로|달러|엔|파운드|프랑|크로나|코루나|루블|헤알|%)"
# 시·군·구로 끝나지만 지명이 아닌 흔한 낱말(주소 오탐 방지)
_NOT_PLACE = (r"(?!(?:다|혹|역|당|동|즉|수|임|항|상|평|잠|반드|가끔|때로|이|그|저|매|몇|한|두|세|네|다섯|여섯|일곱|여덟|아홉|열|열한|열두)시\s)"
              r"(?!(?:연|친|도|요|입|출|가|지|탐|추|기|공|용|강|단|국|영|장|성)구\s)"
              r"(?!(?:장|아|해|공|육|미|국|대|적|아)군\s)")
_ROAD = r"[가-힣0-9]{0,9}[가-힣0-9](?<!으)(?:로|길)"   # '~으로'(조사)는 도로명으로 보지 않는다

PATTERNS = [
    ("메일", "[메일]", re.compile(
        r"[A-Za-z0-9._%+-]+\s*(?:@|＠|\(at\)|\[at\]|골뱅이)\s*[A-Za-z0-9-]+(?:\s*(?:\.|\(dot\)|\[dot\])\s*[A-Za-z0-9-]+)*"
        r"\s*(?:\.|\(dot\)|\[dot\])\s*[A-Za-z]{2,}", re.I)),
    ("링크", "[링크]", re.compile(
        r"(?:https?://|www\.)[^\s가-힣<>\"'()\[\]]+"
        r"|(?<![A-Za-z0-9@.\-])(?:[A-Za-z0-9-]+\.)+(?:com|net|org|kr|io|me|ly|gl|link|be|tv|edu|info|app)\b(?:/[^\s가-힣<>\"'()\[\]]*)?",
        re.I)),
    ("연락처", "[연락처]", re.compile(
        _NB + r"(?:\+82[\s\-.)]*\(?0?|\(?0)\d{1,2}\)?[\s\-.)]*\d{3,4}[\s\-.]*\d{4}(?!\d)"   # 010-1234-5678, 02)123-4567, +82 10…
        r"|" + _NB + r"01[016-9]\d{7,8}(?!\d)"                                            # 01012345678
        r"|" + _NB + r"1[5-9]\d{2}[\s\-.]\d{4}(?!\d)"                                     # 1588-1234 대표번호
        r"|내선\s*(?:번호)?\s*[:：]?\s*\d{3,4}(?!\d)")),                                   # 내선 2678
    ("학번", "[학번]", re.compile(
        r"(?<![A-Za-z0-9])H\d{4}(?!\d)"
        r"|(?<![\d,.\-])\d{9}(?![\d,.\-])(?!" + _MONEY + r")(?!\s+" + _MONEY + r"(?![가-힣]))", re.I)),   # '…원'은 금액, ' 만들어'는 학번
    ("주소", "[주소]", re.compile(
        # 도로명: (광역 이름)? (시·군·구) (읍·면·동)? ○○로/길 숫자(-숫자)
        r"(?:(?:서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|충청[남북]도|전북|전남|전라[남북]도|경북|경남|경상[남북]도|제주)"
        r"(?:특별시|광역시|특별자치시|특별자치도|도|시)?\s*)?"
        r"(?:" + _NOT_PLACE + r"[가-힣]{1,5}(?:시|군|구)\s+){1,2}(?:[가-힣]{1,5}(?:읍|면|동)\s+)?"
        + _ROAD + r"\s*\d{1,4}(?:-\d{1,4})?(?:번길\s*\d{1,4})?(?!\d)(?!" + _UNIT + ")"
        # 지번: (시·군·구) ○○동/리 숫자 — '활동 1등' 같은 낱말과 헷갈리지 않게 번지·부번(-)이 있을 때만
        r"|" + _NOT_PLACE + r"[가-힣]{1,5}(?:시|군|구)\s+(?:[가-힣]{1,5}(?:읍|면)\s+)?[가-힣0-9]{1,6}(?:동|리|\d가)\s*"
        r"\d{1,4}(?:-\d{1,4}(?:번지)?|번지)"
        # 아파트·건물 동호수
        r"|\d{1,4}\s*동\s*\d{1,4}\s*호")),
    ("연락처", "[연락처]", re.compile(
        # 메신저 이름 + (아이디 표시나 @) + 아이디, 또는 숫자·밑줄이 섞인 아이디(카카오 Map 같은 낱말은 제외)
        r"(?:카톡|카카오톡|카카오|오픈채팅|오픈톡|인스타|인스타그램|insta(?:gram)?|텔레그램|라인|디스코드|트위터|페북|페이스북)\s*(?:은|는|도)?\s*"
        r"(?:(?:아이디|아디|id|계정|dm)\s*(?:은|는)?\s*[:：]?\s*@?[A-Za-z0-9_.]{3,}"
        r"|[:：]\s*@?[A-Za-z0-9_.]{3,}"
        r"|@[A-Za-z0-9_.]{3,}"
        r"|(?=[A-Za-z0-9_.]*[\d_])[A-Za-z0-9_.]{3,})"
        r"|(?<![A-Za-z0-9@._])@[A-Za-z0-9_](?:[A-Za-z0-9_.]{1,28}[A-Za-z0-9_])", re.I)),
]


def find(text):
    """가릴 곳 목록 [(종류, 시작, 끝, 원문)]. 쪽지 검사처럼 '무엇이 들어 있나'만 알고 싶을 때 쓴다."""
    out, cur = [], text or ""
    for kind, token, rx in PATTERNS:
        for m in rx.finditer(cur):
            out.append((kind, m.start(), m.end(), m.group()))
        cur = rx.sub(lambda m: "\0" * len(m.group()), cur)   # 같은 자리를 두 번 잡지 않게 길이를 유지한 채 지움
    return sorted(out, key=lambda x: x[1])


def mask(text):
    """연락처·메일·학번·링크·주소를 [연락처]·[메일]·[학번]·[링크]·[주소]로 바꾼 글."""
    if not text:
        return text
    for _, token, rx in PATTERNS:
        text = rx.sub(token, text)
    return text


def _mask_content(c):
    if isinstance(c, str):
        return mask(c)
    if isinstance(c, list):   # Claude 블록형 [{"type": "text", "text": ...}, ...]
        return [{**b, "text": mask(b["text"])} if isinstance(b, dict) and isinstance(b.get("text"), str) else b for b in c]
    return c


def mask_messages(messages):
    """callAI용: [{"role", "content"}] 목록의 content를 가린 새 목록(원본은 그대로)."""
    return [{**m, "content": _mask_content(m.get("content"))} for m in (messages or [])]
