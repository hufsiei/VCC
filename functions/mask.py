def _span(m):
    """가릴 범위. 이름 붙은 그룹 v가 있으면 그 부분만(앞의 '전화' 같은 말은 남긴다)."""
    return m.span("v") if "v" in m.re.groupindex and m.group("v") is not None else m.span()


def _replace(rx, text, make):
    out, last = [], 0
    for m in rx.finditer(text):
        a, b = _span(m)
        out += [text[last:a], make(text[a:b])]
        last = b
    out.append(text[last:])
    return "".join(out)


def find(text):
    """가릴 곳 목록 [(종류, 시작, 끝, 원문)]. 쪽지 검사처럼 '무엇이 들어 있나'만 알고 싶을 때 쓴다."""
    out, cur = [], text or ""
    for kind, token, rx in PATTERNS:
        for m in rx.finditer(cur):
            a, b = _span(m)
            out.append((kind, a, b, text[a:b]))
        cur = _replace(rx, cur, lambda s: "\0" * len(s))   # 같은 자리를 두 번 잡지 않게 길이를 유지한 채 지움
    return sorted(out, key=lambda x: x[1])


def mask(text):
    """연락처·메일·학번·링크·주소를 [연락처]·[메일]·[학번]·[링크]·[주소]로 바꾼 글."""
    if not text:
        return text
    for _, token, rx in PATTERNS:
        text = _replace(rx, text, lambda s, t=token: t)
    return text


def _mask_content(c):
    if isinstance(c, str):
        return mask(c)
    if isinstance(c, list):   # Claude 블록형 [{"type": "text", "text": ...}, ...]
        return [{**b, "text": mask(b["text"])} if isinstance(b, dict) and isinstance(b.get("text"), str) else b for b in c]
    return c


def mask_messages(messages):
    """callAI용: [{"role", "content"}] 목록의 content를 가린 새 목록(원본은 그대로)."""
    return [{**m, "content": _mask_content(m.get("content"))} for m in (messages or [])]
