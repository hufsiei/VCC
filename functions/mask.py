# mask.py — 외부 AI로 나가는 글의 연락처·메일·학번·링크·주소 가리기 (작업 72, 원우)
# 규칙: docs/spec-v1.md 0장 [11/19], PRD 9장 "외부 AI로 나가는 데이터 표"
#   전화(휴대폰·지역번호·대표번호·내선) → [연락처]   메신저 아이디(카톡·인스타 등) → [연락처]
#   이메일 → [메일]   학번(H+숫자 4자리, 9자리 숫자) → [학번]   URL·도메인 → [링크]   국내 주소 → [주소]
# AI에게 판단을 맡기지 않는다. 정규식(코드)으로만 가린다.
# 쓰는 곳: ai.py callAI 입구(messages·system), ai-calls.jsonl 기록 직전. checkMessage(쪽지)는 find()로 종류만 받아 쓴다.
# 시험: cd functions && python test_mask.py
import re

# 숫자 뒤에 이 말이 오면 금액·수량이지 연락처·학번·주소가 아니다(주소는 붙여 쓴 경우만 본다: '107 원룸'은 주소)
_UNIT = r"(?:원|만|천|억|유로|달러|엔|파운드|프랑|크로나|코루나|루블|헤알|개|명|번(?!길)|시간|분|초|주|일|년|월|학기|학년|학점|점|%|가지|군데|살|층|km|m\b|kg)"

# 순서가 중요하다: 메일 → 링크 → 전화 → 학번 → 주소 → 메신저 아이디
PATTERNS = [
    ("메일", "[메일]", re.compile(
        r"[A-Za-z0-9._%+-]+\s*(?:@|＠|\(at\)|\[at\])\s*[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}")),
    ("링크", "[링크]", re.compile(
        r"(?:https?://|www\.)[^\s가-힣<>\"'()\[\]]+"
        r"|(?<![\w@.])(?:[A-Za-z0-9-]+\.)+(?:com|net|org|kr|io|me|ly|gl|link|be|tv|edu|info|app)\b(?:/[^\s가-힣<>\"'()\[\]]*)?",
        re.I)),
    ("연락처", "[연락처]", re.compile(
        r"(?<![\d\w])(?:\+82[\s\-.)]*\(?0?|\(?0)\d{1,2}\)?[\s\-.)]*\d{3,4}[\s\-.]*\d{4}(?![\d])"   # 010-1234-5678, 02)123-4567, +82 10…
        r"|(?<![\d\w])01[016-9]\d{7,8}(?!\d)"                                                    # 01012345678
        r"|(?<![\d\w])1[5-9]\d{2}[\s\-.]\d{4}(?!\d)"                                             # 1588-1234 대표번호
        r"|내선\s*(?:번호)?\s*[:：]?\s*\d{3,4}(?!\d)")),                                         # 내선 2678
    ("학번", "[학번]", re.compile(
        r"(?<![A-Za-z0-9])H\d{4}(?!\d)"
        r"|(?<![\d,.\-])\d{9}(?![\d,.\-])(?!\s*" + _UNIT + ")", re.I)),
    ("주소", "[주소]", re.compile(
        # 도로명: (광역 이름)? (시·군·구) (읍·면·동)? ○○로/길 숫자(-숫자)
        r"(?:(?:서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|충청[남북]도|전북|전남|전라[남북]도|경북|경남|경상[남북]도|제주)"
        r"(?:특별시|광역시|특별자치시|특별자치도|도|시)?\s*)?"
        r"(?:[가-힣]{1,5}(?:시|군|구)\s+){1,2}(?:[가-힣]{1,5}(?:읍|면|동)\s+)?"
        r"[가-힣0-9]{1,10}(?:로|길)\s*\d{1,4}(?:-\d{1,4})?(?:번길\s*\d{1,4})?(?!\d)(?!" + _UNIT + ")"
        # 지번: (시·군·구) ○○동/리 숫자(-숫자)(번지)
        r"|(?:[가-힣]{1,5}(?:시|군|구)\s+)(?:[가-힣]{1,5}(?:읍|면)\s+)?[가-힣0-9]{1,6}(?:동|리|가)\s*\d{1,4}(?:-\d{1,4})?(?:번지|(?!\d)(?!" + _UNIT + "))"
        # 아파트·건물 동호수
        r"|\d{1,4}\s*동\s*\d{1,4}\s*호")),
    ("연락처", "[연락처]", re.compile(
        r"(?:카톡|카카오톡|카카오|오픈채팅|오픈톡|인스타|인스타그램|insta(?:gram)?|텔레그램|라인|디스코드|트위터|페북|페이스북)"
        r"\s*(?:아이디|아디|id|ID|계정|DM)?\s*[:：]?\s*@?[A-Za-z0-9_.]{3,}"
        r"|(?<![\w@.])@[A-Za-z0-9_](?:[A-Za-z0-9_.]{1,28}[A-Za-z0-9_])", re.I)),
]


def find(text):
    """가릴 곳 목록 [(종류, 시작, 끝, 원문)]. 쪽지 검사처럼 '무엇이 들어 있나'만 알고 싶을 때 쓴다."""
    out, cur = [], text or ""
    for kind, token, rx in PATTERNS:
        for m in rx.finditer(cur):
            out.append((kind, m.start(), m.end(), m.group()))
        cur = rx.sub(lambda m: "\0" * len(m.group()), cur)   # 같은 자리를 두 번 잡지 않게 길이를 유지한 채 지움
    return sorted(out, key=lambda x: x[1])


def mask(text):
    """연락처·메일·학번·링크·주소를 [연락처]·[메일]·[학번]·[링크]·[주소]로 바꾼 글."""
    if not text:
        return text
    for _, token, rx in PATTERNS:
        text = rx.sub(token, text)
    return text


def mask_messages(messages):
    """callAI용: [{"role", "content"}] 목록의 content를 가린 새 목록(원본은 그대로)."""
    return [{**m, "content": mask(m.get("content", ""))} if isinstance(m.get("content"), str) else dict(m)
            for m in (messages or [])]
