# mask.py — 외부 AI로 나가는 글의 연락처·메일·학번·링크·주소 가리기 (작업 72, 원우)
# 규칙: docs/spec-v1.md 0장 [11/19], PRD 9장 "외부 AI로 나가는 데이터 표"
#   전화(휴대폰·지역번호·대표번호·내선) → [연락처]   메신저 아이디(카톡·인스타 등) → [연락처]
#   이메일 → [메일]   학번(H+숫자 4자리, 9자리 숫자) → [학번]   URL·도메인 → [링크]   국내 주소 → [주소]
# AI에게 판단을 맡기지 않는다. 정규식(코드)으로만 가린다.
# 쓰는 곳: ai.py callAI 입구(messages·system), ai-calls.jsonl 기록 직전. checkMessage(쪽지)는 find()로 종류만 받아 쓴다.
