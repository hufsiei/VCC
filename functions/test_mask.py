    inserted = 0
    for i, e in enumerate(evidence[::19]):
        for pii, tok in PII:
            head, _, tail = e["text"].partition(" ")
            for src, want in ((f"{head} {pii} {tail}", f"{head} {tok} {tail}"), (f"{e['text']} {pii}", f"{e['text']} {tok}")):
                inserted += 1
                if mask(src) != want:
                    bad.append(f"끼워 넣기 틀림: {e['id']} {pii} → {mask(src)[:80]!r}")

    blocks = [{"role": "user", "content": [{"type": "text", "text": "H0143 010-1234-5678"}, {"type": "image", "source": {}}]}]
    got = mask_messages(blocks)
    if got[0]["content"][0]["text"] != "[학번] [연락처]" or got[0]["content"][1] != {"type": "image", "source": {}} \
            or blocks[0]["content"][0]["text"] != "H0143 010-1234-5678":
        bad.append(f"블록형 mask_messages 틀림: {got}")

    msgs = [{"role": "user", "content": "제 번호 010-1111-2222"}]
    out = mask_messages(msgs)
    if out[0]["content"] != "제 번호 [연락처]" or msgs[0]["content"] != "제 번호 010-1111-2222":
        bad.append(f"mask_messages 틀림: {out} / 원본 {msgs}")
    kinds = [k for k, *_ in find("H0469 010-1234-5678 a@b.com")]
    if kinds != ["학번", "연락처", "메일"]:
        bad.append(f"find 틀림: {kinds}")

    # 붙여 쓴 문장 오탐: 근거 문단의 띄어쓰기를 모두 없애도 바뀌면 안 된다(붙여 쓴 주소 규칙 회귀 시험)
    bad += [f"붙여 쓴 근거 오탐: {e['id']} {find(e['text'].replace(' ', ''))}" for e in evidence
            if mask(e["text"].replace(" ", "")) != e["text"].replace(" ", "")]

    # 주소 조합: 넓은 단위는 그대로, 상세 부분만 [주소] (광역 × 시군구 × 읍면동 × 도로 × 번호 × 띄어쓰기 × 문맥)
    import itertools
    combos = 0
    for m, d, e, r, num, sp, c in itertools.product(
            ["", "서울", "서울특별시", "경기도"], ["동대문구", "용인시 처인구", "중구"], ["", "모현읍", "이문동"],
            ["이문로", "세종대로", "해운대로 570번길", "휴암로12길"], ["107", "12-3", "209번지"], [" ", ""],
            ["{}", "{}에 살아요", "주소는 {}입니다", "({})", "{}, 101동 1203호"]):
        parts = [x.replace(" ", sp) for x in (m, d, e, r) if x]
        src = c.format(sp.join(parts) + sp + num)
        want = c.format(sp.join(parts) + sp + "[주소]").replace("101동 1203호", "[주소]")
        combos += 1
        if mask(src) != want:
            bad.append(f"주소 조합 틀림: {src!r} → {mask(src)!r}")
    inserted += combos

    # 속도: 5만 자 반복 입력이 1초 안에(정규식 되돌아가기 폭주 회귀 시험 — 메일 규칙이 5만 자에 40초 걸렸던 적 있음)
    import time
    for name, s in [("영문", "a" * 50000), ("점", "a." * 25000), ("숫자", "1" * 50000), ("하이픈", "0-" * 25000),
                    ("@", "@a" * 25000), ("메일 앞", "a-" * 25000 + "@"), ("시군구", "동대문구 " * 5000), ("한글", "가 " * 25000)]:
        t = time.time()
        mask(s)
        if time.time() - t > 1:
            bad.append(f"느림: {name} 5만 자 {time.time() - t:.1f}초")

    n = len(MASKED) + len(ORDINARY) + len(evidence) + len(rows) + inserted
    print(f"마스킹 시험 {n}건(치환 {len(MASKED)} · 일반 {len(ORDINARY)} · 근거 {len(evidence)} · 질문 {len(rows)}"
          f" · 끼워 넣기 {inserted}) 중 틀림 {len(bad)}건")
    for b in bad:
        print("  -", b)
    sys.exit(1 if bad else 0)


